import { Injectable } from "@nestjs/common";
import { resolve } from "node:path";
import PDFDocument from "pdfkit";

const COMPANY_LOGO_PATH = resolve(
  __dirname,
  "../../assets/picodesolutions_logo.jpg",
);

// Plain data the PDF needs — easy to test and reuse.
export type JdPdfInput = {
  title: string;
  experience?: string | null;
  location?: string | null;
  employmentType?: string | null;
  responsibilities?: string | null;
  requiredSkills: string[];
  education?: string | null;
  certifications?: string | null;
  languages?: string[];
  jobDescription: string;
};

const ABOUT_PICODE_SYSTEMS =
  "Picode Systems (picode.xyz) is a next-generation technology solutions company delivering enterprise-grade digital transformation services across fintech, healthcare, retail, and data platforms. We specialize in secure application development, data engineering, cloud solutions, and automation-driven QA practices to ensure high-performance and scalable systems for global clients.";

@Injectable()
export class JdPdfService {
  render(input: JdPdfInput): Promise<Buffer> {
    return new Promise((resolve, reject) => {
      const doc = new PDFDocument({
        size: "A4",
        margins: {
          top: 56,
          bottom: 56,
          left: 56,
          right: 56,
        },
        bufferPages: true,
        info: {
          Title: `${input.title} — Job Description`,
          Author: "PiCode Systems",
        },
      });

      // Collect PDF chunks into a single Buffer.
      const chunks: Buffer[] = [];

      doc.on("data", (chunk: Buffer) => chunks.push(chunk));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);

      // Write directly to the page stream so a page break during text rendering
      // does not interrupt PDFKit's active text operation.
      const addPageBackground = () => {
        doc.page.write(
          `q\n0.75686 0.89412 0.96078 rg\n0 0 ${doc.page.width} ${doc.page.height} re\nf\nQ\n`,
        );
      };

      // Paint the background on the first page and every new page.
      doc.on("pageAdded", addPageBackground);
      addPageBackground();

      const logoSize = 64;
      const logoTop = 32;
      doc.image(COMPANY_LOGO_PATH, (doc.page.width - logoSize) / 2, logoTop, {
        fit: [logoSize, logoSize],
      });
      doc.y = logoTop + logoSize + 12;

      const addHeading = (heading: string) => {
        doc
          .font("Helvetica-Bold")
          .fontSize(13)
          .fillColor("#0f172a")
          .text(heading);
        doc.moveDown(0.3);
      };

      const addBullets = (items: string[]) => {
        const cleanedItems = items
          .map((item) => item.replace(/^\s*(?:[-*•]|\d+[.)])\s*/, "").trim())
          .filter(Boolean);

        if (cleanedItems.length > 0) {
          doc
            .font("Helvetica")
            .fontSize(11)
            .fillColor("#0f172a")
            .list(cleanedItems, { bulletRadius: 2 });
        }
      };

      // Header
      doc
        .font("Helvetica-Bold")
        .fontSize(16)
        .fillColor("#0f172a")
        .text(`Job Title: ${input.title}`);

      doc.moveDown();

      // Key details
      const details: [string, string | null | undefined][] = [
        ["Website", "Picode.xyz"],
        ["Experience", input.experience ?? "4–8 Years"],
        ["Location", input.location ?? "Remote / Bangalore (Preferred)"],
        ["Employment Type", input.employmentType ?? "Full-Time"],
      ];

      doc.fontSize(11).fillColor("#0f172a");

      for (const [label, value] of details) {
        if (!value) continue;

        doc.font("Helvetica-Bold").text(`${label}: `, { continued: true });

        doc.font("Helvetica").text(value);
      }

      doc.moveDown();
      addHeading("About Picode Systems");
      doc
        .font("Helvetica")
        .fontSize(11)
        .fillColor("#0f172a")
        .text(ABOUT_PICODE_SYSTEMS, { lineGap: 2 });

      doc.moveDown();
      addHeading("Role Overview");
      doc
        .font("Helvetica")
        .fontSize(11)
        .fillColor("#0f172a")
        .text(input.jobDescription, { lineGap: 2 });

      doc.moveDown();
      addHeading("Key Responsibilities");
      addBullets((input.responsibilities ?? "").split(/\r?\n/));

      doc.moveDown();
      addHeading("Required Skill & Qualifications");
      addBullets([
        ...input.requiredSkills,
        ...(input.education ? [input.education] : []),
        ...(input.certifications ? [input.certifications] : []),
        ...(input.languages ?? []),
      ]);

      // Footer
      doc.moveDown(2);

      doc
        .font("Helvetica")
        .fontSize(8)
        .fillColor("#64748b")
        .text(
          `Generated by PiCode HR on ${new Date().toLocaleDateString("en-GB")}`,
        );

      // Add the watermark to every buffered page after the content.
      // The watermark is white and semi-transparent.
      const pageRange = doc.bufferedPageRange();

      for (
        let pageIndex = pageRange.start;
        pageIndex < pageRange.start + pageRange.count;
        pageIndex++
      ) {
        doc.switchToPage(pageIndex);

        const centerX = doc.page.width / 2;
        const centerY = doc.page.height / 2;

        doc.save();

        doc
          .font("Helvetica")
          .fontSize(42)
          .fillColor("#FFFFFF")
          .fillOpacity(0.45);

        doc.rotate(-35, {
          origin: [centerX, centerY],
        });

        doc.text("PiCode Systems Private Ltd", 0, centerY, {
          width: doc.page.width,
          align: "center",
          lineBreak: false,
        });

        doc.restore();
      }

      doc.end();
    });
  }
}
